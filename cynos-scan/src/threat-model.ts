/**
 * Keeps the repository's threat model current through one standing PR.
 *
 * A full scan of the default branch regenerates the threat model; this opens, or updates, one PR
 * from a fixed branch that writes it to threat-model-path. It is the only operation that needs
 * write permissions, and it runs in its own job, no scanner and no repository code. Its wording
 * changes on every scan because an LLM writes it fresh, so a person decides when to merge.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { isLinkFreeFile } from './target';

export const THREAT_MODEL_BRANCH = 'cynos-scan/threat-model';

/** Repositories commonly reject trailing whitespace and a missing or repeated final newline. */
export function normalize(markdown: string): string {
  const lines = markdown.split(/\r?\n/).map(line => line.trimEnd());
  return `${lines.join('\n').replace(/^\n+|\n+$/g, '')}\n`;
}

export function prBody(target: string, runUrl: string, sha: string): string {
  return [
    `A full cynos-scan run regenerated the repository's threat model: [run](${runUrl}), commit \`${sha.slice(0, 12)}\`.`,
    '',
    `Once merged, the daily diff scans read \`${target}\` as authoritative context (\`--knowledge-base\`). Review it like any other change: the model is generated by an LLM from the code, and its wording changes from scan to scan even when the architecture does not. Merge it when the trust boundaries, entry points and assets it describes are right; close it otherwise. The next full scan updates this same PR.`,
    '',
    'GitHub does not start other workflows for a PR opened by GitHub Actions, so required checks have not run: close and reopen this PR to start them.',
  ].join('\n');
}

export interface PullsApi {
  openPullFrom(branch: string): Promise<number | undefined>;
  createPull(base: string, head: string, title: string, body: string): Promise<string>;
  updatePullBody(number: number, body: string): Promise<void>;
}

type Octokit = ReturnType<typeof import('@actions/github').getOctokit>;

export function octokitPulls(octokit: Octokit, owner: string, repo: string): PullsApi {
  return {
    async openPullFrom(branch) {
      const response = await octokit.rest.pulls.list({
        owner,
        repo,
        head: `${owner}:${branch}`,
        state: 'open',
      });
      return response.data[0]?.number;
    },
    async createPull(base, head, title, body) {
      const response = await octokit.rest.pulls.create({ owner, repo, base, head, title, body });
      return response.data.html_url;
    },
    async updatePullBody(number, body) {
      await octokit.rest.pulls.update({ owner, repo, pull_number: number, body });
    },
  };
}

/**
 * Local Git configuration a fresh actions/checkout writes, plus the identity set here. Anything
 * else could run a program while the token is in Git's environment (a transport through
 * url.*.insteadOf and protocol.ext.allow, a proxy command, an include), so it is refused.
 */
const CHECKOUT_CONFIG =
  /^(core\.(repositoryformatversion|filemode|bare|logallrefupdates|ignorecase|precomposeunicode|symlinks|sparsecheckout|sparsecheckoutcone)|remote\.origin\.(url|fetch|promisor|partialclonefilter)|branch\.\S+\.(remote|merge)|gc\.auto|user\.(name|email)|extensions\.(objectformat|partialclone))$/i;

/**
 * Git's environment here: no system or global configuration, only the checkout's own; and
 * pathspecs taken literally, so threat-model-path names one file even when it holds a glob
 * character (`--` only ends the options).
 */
function gitEnvironment(env: NodeJS.ProcessEnv = process.env): NodeJS.ProcessEnv {
  return {
    ...env,
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_CONFIG_GLOBAL: '/dev/null',
    GIT_LITERAL_PATHSPECS: '1',
  };
}

/** Runs Git in checkout with hooks off: no repository-provided program runs, least of all with the token. */
function git(checkout: string, args: string[], env?: NodeJS.ProcessEnv): string {
  const result = spawnSync('git', ['-C', checkout, '-c', 'core.hooksPath=/dev/null', ...args], {
    encoding: 'utf8',
    env: gitEnvironment(env),
  });
  if (result.status !== 0)
    throw new Error(`git ${args[0]} failed: ${(result.stderr || result.stdout).trim()}`);
  return result.stdout;
}

/** Throws unless the checkout's local Git configuration is what actions/checkout writes. */
export function checkCheckoutConfig(checkout: string): void {
  const names = git(checkout, ['config', '--local', '--list', '--name-only'])
    .split('\n')
    .filter(Boolean);
  const unexpected = [...new Set(names.filter(name => !CHECKOUT_CONFIG.test(name)))];
  if (unexpected.length)
    throw new Error(
      `The checkout has Git configuration a fresh actions/checkout does not write (${unexpected.join(', ')}); update-threat-model needs a fresh checkout with persist-credentials: false.`
    );
}

/**
 * The environment for the push: the token reaches Git as configuration for this push only, not
 * in argv and not stored in .git/config, and only as a header scoped to the remote's own origin.
 */
export function pushEnvironment(remote: string, token: string): NodeJS.ProcessEnv {
  if (!/^https:\/\//.test(remote)) return process.env;
  const basic = Buffer.from(`x-access-token:${token}`).toString('base64');
  return {
    ...process.env,
    GIT_CONFIG_COUNT: '1',
    GIT_CONFIG_KEY_0: `http.${new URL(remote).origin}/.extraheader`,
    GIT_CONFIG_VALUE_0: `AUTHORIZATION: basic ${basic}`,
  };
}

export interface ThreatModelUpdate {
  checkout: string;
  /** Where to push: the repository's own URL, never a remote the checkout configures. */
  remote: string;
  generated: string;
  target: string;
  /** The repository's default branch: the PR's base, and the only branch that updates it. */
  defaultBranch: string;
  token: string;
  runUrl: string;
  /** The scanned commit (GITHUB_SHA): the checkout must be at it. */
  sha: string;
  /** GITHUB_REF: only a run on defaultBranch updates the threat model. */
  ref: string;
  log: (line: string) => void;
}

/** Writes the generated model to target and opens or updates the PR; returns its URL or ''. */
export async function updateThreatModel(
  update: ThreatModelUpdate,
  pulls: PullsApi
): Promise<string> {
  // The branch is the scanned commit of the default branch plus one commit holding the generated
  // file, so the checkout must be at that commit, with nothing staged, and the target must not
  // lead the write outside the repository.
  if (update.ref !== `refs/heads/${update.defaultBranch}`)
    throw new Error(
      `update-threat-model runs only on the default branch, ${update.defaultBranch}, not ${update.ref}.`
    );
  if (git(update.checkout, ['rev-parse', 'HEAD']).trim() !== update.sha)
    throw new Error('The checkout must be at GITHUB_SHA, the commit the scan covered.');
  checkCheckoutConfig(update.checkout);
  if (
    spawnSync('git', ['-C', update.checkout, 'diff', '--cached', '--quiet'], {
      env: gitEnvironment(),
    }).status !== 0
  )
    throw new Error('The checkout has staged changes; update-threat-model needs a fresh checkout.');
  isLinkFreeFile(update.checkout, update.target);
  const destination = join(update.checkout, update.target);
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, normalize(readFileSync(update.generated, 'utf8')));
  const tracked =
    spawnSync('git', ['-C', update.checkout, 'ls-files', '--error-unmatch', '--', update.target], {
      env: gitEnvironment(),
    }).status === 0;
  const changed =
    spawnSync('git', ['-C', update.checkout, 'diff', '--quiet', '--', update.target], {
      env: gitEnvironment(),
    }).status !== 0;
  if (tracked && !changed) {
    update.log(`The threat model on ${update.defaultBranch} is already this one; no PR.`);
    return '';
  }
  git(update.checkout, ['config', 'user.name', 'github-actions[bot]']);
  git(update.checkout, [
    'config',
    'user.email',
    '41898282+github-actions[bot]@users.noreply.github.com',
  ]);
  git(update.checkout, ['checkout', '-B', THREAT_MODEL_BRANCH]);
  git(update.checkout, ['add', '--', update.target]);
  git(update.checkout, [
    'commit',
    '--quiet',
    '--no-verify',
    '-m',
    'Update the threat model from the cynos-scan full scan',
    '-m',
    `Generated by ${update.runUrl} at ${update.sha.slice(0, 12)}.`,
    '--',
    update.target,
  ]);
  git(
    update.checkout,
    [
      'push',
      '--force',
      '--quiet',
      '--no-verify',
      update.remote,
      `HEAD:refs/heads/${THREAT_MODEL_BRANCH}`,
    ],
    pushEnvironment(update.remote, update.token)
  );
  const body = prBody(update.target, update.runUrl, update.sha);
  const open = await pulls.openPullFrom(THREAT_MODEL_BRANCH);
  if (open !== undefined) {
    await pulls.updatePullBody(open, body);
    update.log(`Updated threat-model PR #${open}.`);
    return `#${open}`;
  }
  const url = await pulls.createPull(
    update.defaultBranch,
    THREAT_MODEL_BRANCH,
    'cynos-scan: update the threat model',
    body
  );
  update.log(`Opened ${url}.`);
  return url;
}
